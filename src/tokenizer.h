/* tokenizer.h -- tiktoken/GPT-4 BPE, reading HuggingFace's `tokenizer.json`.
 *
 * Implements docs/16-tokenizer.md.  Four stages, and all four matter:
 *
 *   1. pre-tokenisation by the cl100k regex -- a hand-written state machine,
 *      no regex engine (docs/16: "do not implement a regex engine")
 *   2. ByteLevel: each byte 0..255 becomes a code point through GPT-2's table
 *   3. BPE with `ignore_merges = true` -- if the whole pre-token is in the
 *      vocabulary, use its id directly and apply no merges at all
 *   4. special tokens recognised BEFORE the regex, by exact match
 *
 * A representation trick: instead of converting every pre-token into the
 * ByteLevel alphabet and matching against the vocabulary in that form, the
 * vocabulary is converted back to RAW BYTES at load time.  BPE then operates on
 * the input bytes directly -- one conversion per vocabulary instead of one per
 * token, and no allocation on the hot path.
 *
 * An error here does not blow up: it produces different ids and different output
 * from the oracle, with a perfectly correct forward.  That is why the selftest
 * compares against ids generated by HF's `tokenizers`, and not only against
 * itself.
 */
#ifndef TOOTEGA_TOKENIZER_H
#define TOOTEGA_TOKENIZER_H

#include <stddef.h>
#include <stdint.h>

#include "common.h"

typedef struct {
    const uint8_t *ptr;        /* raw bytes, inside the arena */
    uint32_t       len;
} tt_token;

typedef struct {
    tt_arena  arena;

    tt_token *tokens;          /* id -> bytes */
    int32_t   n_tokens;        /* ids 0..n_tokens-1 of the base vocabulary */
    int32_t   vocab_size;      /* from the config; there is slack at the end (docs/16) */

    /* bytes -> id, open hashing */
    int32_t  *vocab_slots;
    size_t    n_vocab_slots;

    /* (left_id << 32 | right_id) -> rank and resulting id, open hashing.  This
     * is encode's hot loop: a linear scan here costs seconds. */
    uint64_t *merge_keys;
    int32_t  *merge_rank;
    int32_t  *merge_id;
    size_t    n_merge_slots;
    int32_t   n_merges;

    int32_t   byte_id[256];    /* id of the token for a single isolated byte */

    /* specials, matched before the regex */
    tt_token *special;
    int32_t  *special_id;
    int32_t   n_special;
    int32_t   special_min_id;
    /* First byte of any special.  Avoids 36 memcmp per text byte in the scan
     * that slices the input. */
    uint8_t   special_first[256];
} tt_tokenizer;

int  tt_tokenizer_load(tt_tokenizer *t, const char *path, int32_t vocab_size);
void tt_tokenizer_free(tt_tokenizer *t);

/* Returns how many ids were written, or -1 if they did not fit in `max`. */
int64_t tt_encode(const tt_tokenizer *t, const char *text, size_t len,
                  int32_t *out, int64_t max);

/* Bytes written (unterminated), or -1 if they did not fit. */
int64_t tt_decode(const tt_tokenizer *t, const int32_t *ids, int64_t n,
                  char *out, size_t max);

/* Ids above the vocabulary in use exist only as `lm_head` padding and must
 * never be sampled (docs/16). */
int tt_token_is_valid(const tt_tokenizer *t, int32_t id);

int tt_tokenizer_selftest(void);

#endif /* TOOTEGA_TOKENIZER_H */
